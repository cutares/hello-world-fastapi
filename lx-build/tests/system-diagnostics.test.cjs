const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const ts = require('../../source/node_modules/typescript');
const root = path.join(__dirname, '../../source/src');
const source = fs.readFileSync(path.join(root, 'plugins/player/systemQueueDiagnostics.ts'), 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText;
const moduleObject = { exports: {} };
vm.runInNewContext(compiled, { exports: moduleObject.exports, module: moduleObject });
const snapshot = { attempts: 2, successes: 1, lastSuccessItemCount: 17, lastSuccessAt: 1234567890000, lastErrorCategory: 'none', listenersInitialized: true, playerInitialized: true, queueBridgeAvailable: true, diagnosticsBridgeAvailable: true };
const native = { serviceAvailable: true, queueCount: 17, activeItemPresent: true, sessionActive: true, browserRootCalls: 1, browserAccepted: 0, browserRejected: 1, lastBrowserPackage: 'com.android.systemui', lastBrowserUid: 1000, secret: 'SECRET_TOKEN_SENTINEL', title: 'PRIVATE_SONG_SENTINEL', url: 'https://private.example/audio', events: ['SECRET_EVENT_SENTINEL'] };
const text = moduleObject.exports.formatSystemQueueDiagnostics(native, snapshot, 'test', 'ok');
assert.match(text, /原生队列数量：17/);
assert.match(text, /com\.android\.systemui/);
assert.match(text, /浏览允许 \/ 拒绝：0 \/ 1/);
for (const forbidden of ['SECRET_TOKEN_SENTINEL', 'PRIVATE_SONG_SENTINEL', 'https://private.example/audio', 'SECRET_EVENT_SENTINEL']) assert.equal(text.includes(forbidden), false);
const absent = moduleObject.exports.formatSystemQueueDiagnostics(undefined, snapshot, 'test', 'bridge-unavailable');
assert.match(absent, /bridge-unavailable/); assert.match(absent, /原生队列数量：未知/);
const invalid = moduleObject.exports.formatSystemQueueDiagnostics({ queueCount: Infinity, lastBrowserPackage: 'https://private.example/x' }, snapshot, 'test', 'read-failed');
assert.match(invalid, /原生队列数量：未知/); assert.match(invalid, /最近浏览客户端包名：无/); assert.doesNotMatch(invalid, /private\.example/);
const ui = fs.readFileSync(path.join(root, 'screens/Home/Views/Setting/settings/Version.tsx'), 'utf8');
assert.match(ui, /onPress=\{\(\) => \{ void readDiagnostics\(\)/);
assert.match(ui, /clipboardWriteText\(diagnostics\)/);
assert.doesNotMatch(ui, /setInterval|setTimeout|fetch\(|httpGet|\.then\(readDiagnostics/);
assert.match(ui, /useEffect\(\(\) => \{\s*mounted\.current = true\s*return/);
console.log('PASS: allowlisted snapshot formatting, bridge absence/failure, no raw native data leakage, manual-only capture and local copy.');
